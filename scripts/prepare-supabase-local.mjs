import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const source = path.resolve(root, "packages", "db", "migrations");
const destination = path.resolve(root, "supabase", "migrations");
if (!source.startsWith(root) || !destination.startsWith(root)) throw new Error("Unsafe migration path");

// The hosted project predates Supabase's 2025 "secure by default" change, so
// there every object created by `postgres` (i.e. every migration) is granted
// to anon/authenticated/service_role automatically, and migrations narrow that
// baseline with explicit revokes (0029/0030/0031/0035/0039/0040/0041…). New
// local/CI images ship WITHOUT those default grants, which would make the same
// migrations produce a different privilege model than production. This
// bootstrap sorts before 0000_init.sql and restores the legacy baseline first,
// so the copied migrations behave identically everywhere.
const LEGACY_PRIVILEGES_BOOTSTRAP = `-- Generated by scripts/prepare-supabase-local.mjs — do not edit.
-- Mirrors the legacy hosted default privileges for objects the migrations
-- create as the postgres role. Runs before the first real migration.
grant usage on schema public to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant all on tables to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant all on sequences to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant all on functions to anon, authenticated, service_role;
`;

await mkdir(destination, { recursive: true });
for (const entry of await readdir(destination, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith(".sql")) await rm(path.join(destination, entry.name));
}
await writeFile(path.join(destination, "00000000000000_legacy_default_privileges.sql"), LEGACY_PRIVILEGES_BOOTSTRAP);
for (const entry of await readdir(source, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith(".sql")) {
    await copyFile(path.join(source, entry.name), path.join(destination, entry.name));
  }
}
