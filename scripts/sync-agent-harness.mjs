#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_MARKER = "<!-- GENERATED by scripts/sync-agent-harness.mjs. DO NOT EDIT. -->";
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(repoRoot, ".claude", "skills");
const targetRoot = join(repoRoot, ".agents", "skills");
const agentsFile = join(repoRoot, "AGENTS.md");
const checkOnly = process.argv.includes("--check");

function frontmatter(content, sourcePath) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!match) throw new Error(`Missing YAML frontmatter: ${sourcePath}`);
  return match[1].replace(/\r\n/g, "\n");
}

function bridgeFor(skill, sourcePath) {
  const canonical = readFileSync(sourcePath, "utf8");
  return `---\n${frontmatter(canonical, sourcePath)}\n---\n\n${GENERATED_MARKER}\n\n# Shared skill bridge\n\nThe canonical instructions for this skill live at\n\`../../../.claude/skills/${skill}/SKILL.md\`. Read that file completely before\ntaking task actions, resolve its relative references from the canonical skill\ndirectory, and follow it as authoritative.\n`;
}

function canonicalSection(relativePath) {
  const path = join(repoRoot, relativePath);
  if (!existsSync(path)) return "";
  const content = readFileSync(path, "utf8").trim().replace(/\r\n/g, "\n");
  return content ? `\n\n===== ${relativePath} =====\n\n${content}` : "";
}

function rootAgentsFile() {
  const sources = ["CLAUDE.md"];
  for (const app of ["apps/web/CLAUDE.md", "apps/mobile/CLAUDE.md"]) {
    if (existsSync(join(repoRoot, app))) sources.push(app);
  }

  const rulesRoot = join(repoRoot, ".claude", "rules");
  if (existsSync(rulesRoot)) {
    for (const file of readdirSync(rulesRoot)
      .filter((name) => name.endsWith(".md"))
      .sort()) {
      sources.push(`.claude/rules/${file}`);
    }
  }

  const preamble = `# Codex harness

${GENERATED_MARKER}

This file is a generated Codex view of the canonical Claude/Codex repository
contracts below. Never edit this file manually. Update the matching
\`CLAUDE.md\` or \`.claude/rules/*.md\` source, then run
\`npm run harness:sync\`.

Canonical skill content lives only in \`.claude/skills/*\`.
\`.agents/skills/*/SKILL.md\` files are generated discovery bridges. Load every
skill required by the contracts below before taking task actions. In
particular, use \`marketing-page\` for marketing paths, \`product-screen\` for
authenticated product paths, and \`mobile-screen\` for mobile screen work. Run
\`marketing-verify\` after substantial marketing work.

Canonical hook implementations live only in \`.claude/hooks/*\` and support
both agents. Codex discovers them through \`.codex/config.toml\`. Treat every
\`MARKETING LINT\` hook warning as mandatory: fix hard violations before
continuing and review advisories before the final response. After changing any
harness source, run \`npm run harness:check\` and \`npm run harness:test\`.

Path frontmatter in the included rule files defines their scope.`;

  return `${preamble}${sources.map(canonicalSection).filter(Boolean).join("")}\n`;
}

function skillNames(root) {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(root, entry.name, "SKILL.md")))
    .map((entry) => entry.name)
    .sort();
}

function removeGeneratedSkill(skill) {
  const directory = resolve(targetRoot, skill);
  const rel = relative(targetRoot, directory);
  if (!rel || rel.startsWith("..") || rel.includes(":")) throw new Error(`Unsafe generated path: ${directory}`);
  const skillFile = join(directory, "SKILL.md");
  const content = existsSync(skillFile) ? readFileSync(skillFile, "utf8") : "";
  if (!content.includes(GENERATED_MARKER)) {
    throw new Error(`Refusing to remove non-generated Codex skill: ${skillFile}`);
  }
  rmSync(directory, { recursive: true, force: true });
}

const sourceSkills = skillNames(sourceRoot);
const expected = new Map(sourceSkills.map((skill) => [skill, bridgeFor(skill, join(sourceRoot, skill, "SKILL.md"))]));
const stale = [];
const expectedAgentsFile = rootAgentsFile();
const currentAgentsFile = existsSync(agentsFile) ? readFileSync(agentsFile, "utf8") : null;

if (currentAgentsFile !== expectedAgentsFile) {
  stale.push("AGENTS.md");
  if (!checkOnly) writeFileSync(agentsFile, expectedAgentsFile, "utf8");
}

for (const [skill, bridge] of expected) {
  const target = join(targetRoot, skill, "SKILL.md");
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (current !== bridge) stale.push(skill);
  if (!checkOnly && current !== bridge) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, bridge, "utf8");
  }
}

const removed = skillNames(targetRoot).filter((skill) => !expected.has(skill));
if (!checkOnly) removed.forEach(removeGeneratedSkill);

if (checkOnly && (stale.length || removed.length)) {
  if (stale.length) console.error(`Stale or missing Codex skill bridges: ${stale.join(", ")}`);
  if (removed.length) console.error(`Orphaned Codex skill bridges: ${removed.join(", ")}`);
  console.error("Run `npm run harness:sync` and commit the generated changes.");
  process.exit(1);
}

if (!checkOnly) {
  console.log(`Codex harness synchronized (${sourceSkills.length} skills).`);
} else {
  console.log(`Codex harness is synchronized (${sourceSkills.length} skills).`);
}
